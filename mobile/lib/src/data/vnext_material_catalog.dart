class VNextMaterialCatalog {
  static final packs = _seeds.map(_buildPack).toList(growable: false);

  static ScenarioPack _buildPack(_PackSeed seed) {
    final isInformation = seed.category == '轻信息类 / 轻新闻类';
    const dialogueRoles = ['开场句', '核心目标句', '回应句', '补充句', '收尾句'];
    const informationRoles = ['主题引入句', '关键信息句', '补充事实句', '原因 / 影响句', '结尾总结句'];
    final roles = isInformation ? informationRoles : dialogueRoles;

    return ScenarioPack(
      id: seed.id,
      title: seed.title,
      category: seed.category,
      difficulty: seed.difficulty,
      summary: seed.summary,
      sceneDescription: '这个场景重点练${seed.goal}。',
      durationLabel: '15 到 30 分钟',
      reviewHeadline: '练完后优先复盘本场景的高频词块和可复用整句。',
      sentences: [
        for (final entry in seed.lines.indexed)
          _buildSentence(
            packId: seed.id,
            line: entry.$2,
            index: entry.$1,
            role: roles[entry.$1],
            isInformation: isInformation,
            difficulty: seed.difficulty,
          ),
      ],
    );
  }

  static SentenceNote _buildSentence({
    required String packId,
    required _LineSeed line,
    required int index,
    required String role,
    required bool isInformation,
    required String difficulty,
  }) {
    final vocabulary = _vocabularyFor(line, difficulty: difficulty);
    return SentenceNote(
      id: '$packId-s${index + 1}',
      english: line.english,
      chinese: line.chinese,
      speaker: isInformation || index.isEven
          ? DialogueSpeaker.speakerA
          : DialogueSpeaker.speakerB,
      role: role,
      scenePrompt: line.chinese,
      keywords: vocabulary,
      chunk: line.focus,
      pattern: line.pattern,
      dictationHint: '注意写全 ${line.focus}，并检查句子语序。',
      recallHint: '根据“${line.chinese}”完整说出英文，不只说关键词。',
    );
  }

  static List<KeywordNote> _vocabularyFor(
    _LineSeed line, {
    required String difficulty,
  }) {
    final focusWords = _tokens(line.focus)
        .map((item) => item.toLowerCase())
        .where((word) => !_stopWords.contains(word))
        .toList();
    final sentenceWords = _tokens(line.english)
        .map((item) => item.toLowerCase())
        .where((word) => !_stopWords.contains(word))
        .toList();
    final focusWordsWithGloss = focusWords
        .where(vnextVocabularyGlosses.containsKey)
        .toList();
    final sentenceWordsWithGloss = sentenceWords
        .where(vnextVocabularyGlosses.containsKey)
        .toList();
    final headPool = focusWordsWithGloss.isNotEmpty
        ? focusWordsWithGloss
        : sentenceWordsWithGloss.isNotEmpty
        ? sentenceWordsWithGloss
        : focusWords.isNotEmpty
        ? focusWords
        : sentenceWords;
    final headWord = headPool.reduce(
      (current, next) => next.length > current.length ? next : current,
    );
    final minimumLength = switch (difficulty) {
      '轻挑战' => 4,
      '进阶' => 5,
      _ => 6,
    };
    final candidates = sentenceWords
        .where(
          (word) =>
              word == headWord ||
              (vnextVocabularyGlosses.containsKey(word) &&
                  (focusWords.contains(word) ||
                      word.replaceAll(RegExp(r"[-']"), '').length >=
                          minimumLength)),
        )
        .toList();

    if (candidates.isEmpty) {
      candidates.add(headWord);
    }

    final seen = <String>{};
    final unique = candidates
        .where((word) => seen.add(word.toLowerCase()))
        .toList();
    unique.sort((a, b) {
      final aFocus = focusWords.contains(a) ? 1 : 0;
      final bFocus = focusWords.contains(b) ? 1 : 0;
      if (aFocus != bFocus) return bFocus.compareTo(aFocus);
      return b.length.compareTo(a.length);
    });

    return unique
        .map(
          (word) => KeywordNote(
            word: word,
            phonetic:
                vnextVocabularyPhonetics[word] ??
                generatedVocabularyPhonetics[word] ??
                '',
            meaning:
                vnextVocabularyGlosses[word] ?? '${line.focusMeaning}（词块核心词）',
            wordRoot: vnextVocabularyFormations[word] ?? '',
            collocations:
                vnextVocabularyCollocations[word]?.keys.toList(
                  growable: false,
                ) ??
                const [],
            collocationMeanings: vnextVocabularyCollocations[word] ?? const {},
            confusingPoint: vnextVocabularyConfusingPoints[word] ?? '',
            example: line.english,
            partOfSpeech:
                vnextVocabularyPartsOfSpeech[word] ??
                generatedVocabularyPartsOfSpeech[word] ??
                '',
          ),
        )
        .toList(growable: false);
  }

  static List<String> _tokens(String sentence) {
    return RegExp(r"[A-Za-z]+(?:[-'][A-Za-z]+)*")
        .allMatches(sentence)
        .map((match) => match.group(0)!)
        .toList(growable: false);
  }

